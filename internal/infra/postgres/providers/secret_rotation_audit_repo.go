package providers

import (
	"context"
	"time"

	domain "github.com/guliangiam/guliangiam/internal/domain/providers"
	"github.com/guliangiam/guliangiam/internal/infra/postgres/shared"
)

type SecretRotationAuditRepository struct {
	db shared.DBTX
}

func NewSecretRotationAuditRepository(db shared.DBTX) *SecretRotationAuditRepository {
	return &SecretRotationAuditRepository{db: db}
}

const queryInsertSecretRotationAudit = `
INSERT INTO guliangiam.secret_rotation_audit (id, provider_id, secret_type, old_version, new_version, rotated_by, rotated_at, reason)
VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
`

const queryListSecretRotationAudits = `
SELECT id, provider_id, secret_type, old_version, new_version, rotated_by, rotated_at, reason
FROM guliangiam.secret_rotation_audit
WHERE provider_id = $1
ORDER BY rotated_at DESC
LIMIT $2
`

func (r *SecretRotationAuditRepository) Create(ctx context.Context, audit *domain.SecretRotationAudit) error {
	_, err := r.db.Exec(ctx, queryInsertSecretRotationAudit,
		audit.ID, audit.ProviderID, audit.SecretType,
		audit.OldVersion, audit.NewVersion, audit.RotatedBy,
		audit.RotatedAt, audit.Reason,
	)
	return err
}

func (r *SecretRotationAuditRepository) ListByProviderID(ctx context.Context, providerID string, limit int) ([]domain.SecretRotationAudit, error) {
	if limit <= 0 {
		limit = 20
	}
	rows, err := r.db.Query(ctx, queryListSecretRotationAudits, providerID, limit)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	items := make([]domain.SecretRotationAudit, 0)
	for rows.Next() {
		var a domain.SecretRotationAudit
		var rotatedBy *string
		var reason *string
		if err := rows.Scan(
			&a.ID, &a.ProviderID, &a.SecretType,
			&a.OldVersion, &a.NewVersion, &rotatedBy,
			&a.RotatedAt, &reason,
		); err != nil {
			return nil, err
		}
		if rotatedBy != nil {
			a.RotatedBy = *rotatedBy
		}
		if reason != nil {
			a.Reason = *reason
		}
		items = append(items, a)
	}
	if rowsErr := rows.Err(); rowsErr != nil {
		return nil, rowsErr
	}

	return items, nil
}

func RecordSecretRotation(ctx context.Context, repo *SecretRotationAuditRepository, providerID, secretType string, oldVersion, newVersion int, rotatedBy, reason string) error {
	audit := &domain.SecretRotationAudit{
		ID:         "", // Will be generated by DB
		ProviderID: providerID,
		SecretType: secretType,
		OldVersion: oldVersion,
		NewVersion: newVersion,
		RotatedBy:  rotatedBy,
		RotatedAt:  time.Now().UTC(),
		Reason:     reason,
	}
	return repo.Create(ctx, audit)
}
