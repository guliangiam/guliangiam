func redirectURIsOfLength(count, length int) []string {
	prefix := "https://example.com/"
	uris := make([]string, 0, count)
	for i := 0; i < count; i++ {
		uri := fmt.Sprintf("%scb/%d", prefix, i)
		if pad := length - len(uri); pad > 0 {
			uri += "/" + strings.Repeat("a", pad-1)
		}
		uris = append(uris, uri)
	}
	return uris
}

