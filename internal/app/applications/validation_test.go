func TestValidateSamlMetadata(t *testing.T) {
	require := func(t *testing.T, err error, wantErr bool) *apperrors.Error {
		t.Helper()
		if !wantErr {
			if err != nil {
				t.Fatalf("unexpected error: %v", err)
			}
			return nil
		}
		return assertAppError(t, err, apperrors.CodeUnprocessableEntity)
	}

	entityDescriptor := `<EntityDescriptor xmlns="urn:oasis:names:tc:SAML:2.0:metadata" entityID="https://idp.example.com"/>`
	require(t, validateSamlMetadata(""), false)
	require(t, validateSamlMetadata("   "), false)
	require(t, validateSamlMetadata(entityDescriptor), false)
	require(t, validateSamlMetadata("<EntitiesDescriptor/>"), false)
	require(t, validateSamlMetadata(`<?xml version="1.0"?><EntityDescriptor entityID="x"/>`), false)

	appErr := require(t, validateSamlMetadata("<EntityDescriptor"), true)
	if appErr.Meta[metaKeyField] != "samlMetadata" || appErr.Meta[metaKeyFormat] != "xml" {
		t.Fatalf("meta = %+v", appErr.Meta)
	}

	appErr = require(t, validateSamlMetadata("<Assertion/>"), true)
	if appErr.Meta[metaKeyField] != "samlMetadata" || appErr.Meta[metaKeyValue] != "Assertion" {
		t.Fatalf("meta = %+v", appErr.Meta)
	}

	appErr = require(t, validateSamlMetadata(`<EntityDescriptor xmlns="urn:example:wrong"/>`), true)
	if appErr.Meta[metaKeyField] != "samlMetadata" || appErr.Meta[metaKeyValue] != "urn:example:wrong" {
		t.Fatalf("meta = %+v", appErr.Meta)
	}

	appErr = require(t, validateSamlMetadata(`<?xml version="1.0"?>`), true)
	if appErr.Meta[metaKeyField] != "samlMetadata" {
		t.Fatalf("meta = %+v", appErr.Meta)
	}

	multiKB := `<EntityDescriptor xmlns="urn:oasis:names:tc:SAML:2.0:metadata"><IDPSSODescriptor>` +
		strings.Repeat("<!-- padding -->", 512) + `</IDPSSODescriptor></EntityDescriptor>`
	require(t, validateSamlMetadata(multiKB), false)
}

