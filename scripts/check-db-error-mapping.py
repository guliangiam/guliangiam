#!/usr/bin/env python3
"""Report PostgreSQL repository write paths that still return a bare driver error.

Why this exists
---------------
E1-B4a added one mapper (`internal/infra/postgres/pgerror`) for constraint
errors and wired it into four domains. The remaining repositories still hand a
raw `*pgconn.PgError` to the application layer, which PresentError renders as an
opaque 500. A full sweep is a separate batch, so this script measures the
backlog instead of blocking CI on it.

Rules
-----
  * Scope: production Go files under `internal/infra/postgres`. A file is a
    repository file when its basename contains `repository`, starts with
    `repo_`, or ends with `_repo.go`.
  * A write function is a function whose body calls `.Exec(` (all repository
    Exec calls are writes) or calls `.QueryRow(` together with a SQL constant
    classified as INSERT/UPDATE/DELETE.
  * A bare return is a `return err` / `return nil, err` (or another tuple ending
    in `err`) that appears after the first write call and is not wrapped by
    `pgerror.Map`. Returns before the write call (JSON marshaling) do not count.
  * This is a text/AST-lite heuristic, not a type checker: it deliberately
    under-reports rather than guessing about aliases.

Baseline
--------
`scripts/db-error-mapping-baseline.txt` is the accepted backlog and is always
generated by this script (`--write-baseline`), never edited by hand. The script
is report-only: new entries do not fail the run. When a domain is converted,
regenerate the baseline so the file records the smaller backlog.

输入：internal/infra/postgres/**/*.go（排除 _test.go）
输出：扫描文件数 / 写函数数 / 裸 return 函数与站点数 / 基线差异
--check 行为：无 --check；始终 exit 0（只报告，不阻断 CI）
消费方：独立脚本、E1-B4a 后续批次评估
"""

import argparse
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCAN_ROOT = ROOT / "internal/infra/postgres"
BASELINE = ROOT / "scripts/db-error-mapping-baseline.txt"

WRITE_SQL = re.compile(r"(?is)^\s*(INSERT|UPDATE|DELETE)\b")
RAW_CONST = re.compile(r"\b([A-Za-z_]\w*)\s*=\s*`([^`]*)`")
FUNC = re.compile(r"\bfunc\s+(?:\(\s*([^)]*)\s*\)\s*)?([A-Za-z_]\w*)\s*\(")
RETURN = re.compile(r"\breturn\s+([^\n;{}]*)")


def repository_files():
    for path in sorted(SCAN_ROOT.rglob("*.go")):
        if path.name.endswith("_test.go"):
            continue
        name = path.name.lower()
        if "repository" in name or name.startswith("repo_") or name.endswith("_repo.go"):
            yield path


def mask_source(source):
    """Blank comments and literals while preserving offsets and newlines."""
    out = []
    i = 0
    n = len(source)
    while i < n:
        c = source[i]
        if source.startswith("//", i):
            while i < n and source[i] != "\n":
                out.append(" ")
                i += 1
            continue
        if source.startswith("/*", i):
            out.append("  ")
            i += 2
            while i < n and not source.startswith("*/", i):
                out.append("\n" if source[i] == "\n" else " ")
                i += 1
            if i < n:
                out.append("  ")
                i += 2
            continue
        if c == '"' or c == "'":
            quote = c
            out.append(" ")
            i += 1
            while i < n:
                if source[i] == "\\":
                    out.append("  " if i + 1 < n and source[i + 1] != "\n" else " ")
                    i += 2
                    continue
                if source[i] == quote:
                    out.append(" ")
                    i += 1
                    break
                out.append("\n" if source[i] == "\n" else " ")
                i += 1
            continue
        if c == "`":
            out.append(" ")
            i += 1
            while i < n:
                if source[i] == "`":
                    out.append(" ")
                    i += 1
                    break
                out.append("\n" if source[i] == "\n" else " ")
                i += 1
            continue
        out.append(c)
        i += 1
    return "".join(out)


def write_sql_names(paths):
    """Collect SQL constant names whose body starts with a write verb."""
    names = set()
    for path in paths:
        source = path.read_text(encoding="utf-8")
        for match in RAW_CONST.finditer(source):
            if WRITE_SQL.match(match.group(2)):
                names.add(match.group(1))
    return names


def receiver_type(receiver):
    """Return the receiver type without the variable name or pointer marker."""
    if not receiver:
        return ""
    tokens = receiver.replace("*", " ").split()
    return tokens[-1] if tokens else ""


def function_bodies(masked):
    """Yield (method, body_start, body) for every top-level func declaration.

    method is `ReceiverType.Name` for methods, so two receiver types in one
    file (aigateway) do not collapse into one baseline entry.
    """
    for match in FUNC.finditer(masked):
        receiver = receiver_type(match.group(1))
        name = match.group(2)
        method = f"{receiver}.{name}" if receiver else name
        brace = masked.find("{", match.end())
        if brace == -1:
            continue
        depth = 0
        end = -1
        for i in range(brace, len(masked)):
            if masked[i] == "{":
                depth += 1
            elif masked[i] == "}":
                depth -= 1
                if depth == 0:
                    end = i
                    break
        if end == -1:
            continue
        yield method, brace, masked[brace + 1 : end]


def first_write_call(body, write_names):
    positions = [m.start() for m in re.finditer(r"\.Exec\s*\(", body)]
    for match in re.finditer(r"\.QueryRow\s*\(", body):
        window = body[match.start() : match.start() + 240]
        if any(re.search(r"\b" + re.escape(name) + r"\b", window) for name in write_names):
            positions.append(match.start())
    return min(positions) if positions else None


def bare_error_returns(body, after):
    sites = []
    for match in RETURN.finditer(body):
        if match.start() <= after:
            continue
        expression = match.group(1).strip()
        if expression == "err" or expression.endswith(", err"):
            sites.append(match.start())
    return sites


def scan():
    paths = list(repository_files())
    write_names = write_sql_names(paths)
    findings = []
    write_functions = 0
    scanned = 0
    for path in paths:
        scanned += 1
        source = path.read_text(encoding="utf-8")
        masked = mask_source(source)
        rel = os.path.relpath(path, ROOT)
        for name, body_start, body in function_bodies(masked):
            write_at = first_write_call(body, write_names)
            if write_at is None:
                continue
            write_functions += 1
            sites = bare_error_returns(body, write_at)
            if sites:
                line = source[: body_start + 1 + sites[0]].count("\n") + 1
                findings.append((rel, name, line, len(sites)))
    return scanned, write_functions, findings


def read_baseline():
    if not BASELINE.exists():
        return set()
    entries = set()
    for line in BASELINE.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        entries.add(line)
    return entries


def write_baseline(findings):
    lines = [
        "# db-error-mapping baseline — generated by scripts/check-db-error-mapping.py --write-baseline",
        "# Entry format: <file>|<function>. This is the accepted bare-return backlog, not a manual count.",
        f"# total={len(findings)}",
    ]
    lines.extend(f"{rel}|{name}" for rel, name, _line, _sites in findings)
    BASELINE.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--write-baseline",
        action="store_true",
        help="regenerate scripts/db-error-mapping-baseline.txt from the current scan",
    )
    args = parser.parse_args()

    scanned, write_functions, findings = scan()
    current = {f"{rel}|{name}" for rel, name, _line, _sites in findings}
    sites = sum(item[3] for item in findings)

    print("db-error-mapping report (report-only, exit 0)")
    print(f"  repository files scanned: {scanned}")
    print(f"  write functions:          {write_functions}")
    print(f"  bare-return functions:    {len(findings)}")
    print(f"  bare-return sites:        {sites}")
    print(f"  baseline file:            {os.path.relpath(BASELINE, ROOT)}")

    if args.write_baseline:
        write_baseline(findings)
        print(f"  baseline written:         {len(findings)} entries")
        print("  note: rerun without --write-baseline to compare")
        return 0

    baseline = read_baseline()
    new = sorted(current - baseline)
    fixed = sorted(baseline - current)
    print(f"  baseline entries:         {len(baseline)}")
    print(f"  new entries:              {len(new)}")
    print(f"  fixed entries:            {len(fixed)}")

    if findings:
        print("  current backlog:")
        for rel, name, line, count in findings:
            print(f"    - {rel}:{line} {name} ({count} bare return(s))")
    if new:
        print("  new (not a CI failure; regenerate the baseline when intentional):")
        for entry in new:
            print(f"    + {entry}")
    if fixed:
        print("  fixed (regenerate the baseline to record the smaller backlog):")
        for entry in fixed:
            print(f"    - {entry}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
