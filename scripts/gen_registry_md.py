#!/usr/bin/env python3
"""gen_registry_md.py — 从 contracts/registries/*.yaml 生成人类可读 Markdown

唯一事实源：contracts/registries/*.yaml
生成物：
  docs/generated/*-registry.md    (naming-registry.md 等)
  docs/generated/security-readiness.md

生成物头部统一声明"自动生成、渲染层、禁止手改"，CI 以 --check 零差异门禁拦截漂移。

Usage:
  python3 scripts/gen_registry_md.py           # 生成全部
  python3 scripts/gen_registry_md.py --check   # 零差异门禁
  python3 scripts/gen_registry_md.py --only naming   # 只生成 naming.yaml 对应的 md

输入：contracts/registries/*.yaml
输出：docs/generated/*-registry.md + security-readiness.md；--check 模式零差异门禁
--check 行为：--check 模式比较各注册表 md 与 YAML 重新渲染结果的差异，无差异时 PASS
消费方：check-generated-zero-diff.sh、CI
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

import yaml  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
YAML_DIR = ROOT / "contracts" / "registries"   # YAML 唯一事实源
MD_DIR = ROOT / "docs" / "generated"            # 渲染层 .md 输出目录

# YAML 文件名 → 对应 md 渲染文件名 + 人类可读标题
REGISTRY_MAP = {
    "naming.yaml": ("naming-registry.md", "术语与命名注册表（Naming Registry）"),
    "state-machines.yaml": ("state-machine-registry.md", "状态机注册表（State Machine Registry）"),
    "errors.yaml": ("errors-registry.md", "错误码注册表（Error Code Registry）"),
    "env.yaml": ("env-registry.md", "环境变量注册表（Environment Variable Registry）"),
    "limits.yaml": ("limit-registry.md", "限流器参数注册表（Rate Limit Registry）"),
    "slo.yaml": ("slo-registry.md", "SLO / 错误预算注册表（SLO / Error Budget Registry）"),
    "cache.yaml": ("cache-registry.md", "缓存参数注册表（Cache Registry）"),
    "outbox.yaml": ("outbox-registry.md", "Outbox 参数注册表（Outbox Registry）"),
    "surfaces.yaml": ("surfaces-registry.md", "API 契约注册表（API Contract Registry）"),
    "provider-kinds.yaml": ("provider-kinds-registry.md", "Provider Kind 路由注册表（Provider Kind Registry）"),
    "open-items.yaml": ("open-item-registry.md", "开放项注册表（Open Item Registry）"),
    "lifecycle.yaml": ("lifecycle-registry.md", "数据生命周期注册表（Data Lifecycle Registry）"),
    "security-readiness.yaml": ("security-readiness.md", "安全能力就绪度矩阵（Security Readiness Matrix）"),
    "events.yaml": ("event-registry.md", "事件域注册表（Event Registry）"),
    "permissions.yaml": ("permissions-registry.md", "Casbin 权限点注册表（Permissions Registry）"),
    "known-red.yaml": ("known-red-registry.md", "问题与风险清单（Known-Red Risk Register）"),
    "referential-integrity.yaml": ("referential-integrity-registry.md", "表间引用完整性裁决（Referential Integrity Registry）"),
    "crypto.yaml": ("crypto-registry.md", "加密能力位注册表（Crypto Capability Registry）"),
}


def _source_digest(yaml_name: str) -> str:
    """渲染层指纹 = 源 YAML 内容的 SHA-256 前 12 位。

    这里刻意**不写生成日期**：日期每天都变，会让「渲染层与 YAML 零差异」这条门禁在每次
    UTC 跨日后无端变红（内容没改也要重新生成），门禁噪声最终会训练人忽略它。指纹只在
    源头内容变化时才变，正好等于这条门禁想表达的东西——「渲染层是否跟上了 YAML」。
    """
    path = YAML_DIR / yaml_name
    if not path.exists():
        return "missing"
    return hashlib.sha256(path.read_bytes()).hexdigest()[:12]


def _header(title: str, yaml_name: str) -> str:
    digest = _source_digest(yaml_name)
    return (
        f"# {title}\n"
        f"\n"
        f"<!--\n"
        f"  ⚠️ AUTO-GENERATED by scripts/gen_registry_md.py\n"
        f"  ⚠️ Source: {yaml_name} (唯一事实源)\n"
        f"  ⚠️ Do NOT edit this file manually. Run `python3 scripts/gen_registry_md.py` to regenerate.\n"
        f"  ⚠️ Source-SHA256: {digest}\n"
        f"-->\n"
        f"\n"
        f"- **唯一事实源**：`contracts/registries/{yaml_name}`（YAML 机器可读）\n"
        f"- **本文件定位**：人类可读渲染层，由生成器产出，禁止手改。\n"
        f"  修改必须先改 YAML，再运行 `python3 scripts/gen_registry_md.py`。\n"
    )


def _render_value(v, indent: int = 0) -> str:
    """渲染单个值（递归处理 dict/list/scalar）。"""
    pad = " " * indent
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "`true`" if v else "`false`"
    if isinstance(v, (int, float)):
        return f"`{v}`"
    if isinstance(v, str):
        # 多行字符串用代码块
        if "\n" in v:
            return f"\n```text\n{v}\n```"
        return v
    if isinstance(v, list):
        if not v:
            return "_（空）_"
        parts = []
        for item in v:
            if isinstance(item, dict):
                parts.append("")
                parts.append(_render_dict_inline(item, indent + 2))
            else:
                parts.append(f"{pad}- {_render_value(item, indent + 2)}")
        return "\n".join(parts)
    if isinstance(v, dict):
        return _render_dict(v, indent)
    return str(v)


def _render_dict_inline(d: dict, indent: int) -> str:
    """紧凑渲染一个 dict（用于 list of dict 的列表项）。"""
    pad = " " * indent
    # 优先把短字段放同一行，长字段换行
    parts = []
    for i, (k, v) in enumerate(d.items()):
        label = f"**{k}**: "
        rendered = _render_value(v, indent + 4)
        if "\n" in rendered:
            # 长值换行
            parts.append(f"{pad}{label}")
            parts.append(rendered)
        else:
            parts.append(f"{pad}{label}{rendered}")
    return "\n".join(parts)


def _render_dict(d: dict, indent: int = 0) -> str:
    pad = " " * indent
    if not d:
        return f"{pad}_（空）_"
    parts = []
    for k, v in d.items():
        label = f"{pad}- **{k}**: "
        rendered = _render_value(v, indent + 2)
        if rendered.startswith("\n"):
            parts.append(label.rstrip())
            parts.append(rendered.lstrip("\n"))
        elif "\n" in rendered:
            parts.append(label.rstrip())
            parts.append(rendered)
        else:
            parts.append(label + rendered)
    return "\n".join(parts)


def _render_table(rows: list[dict], indent: int = 0) -> str:
    """把 list[dict] 渲染为 Markdown 表格。所有 dict 必须有相同 key 集合。"""
    if not rows:
        return "_（空）_"
    keys = list(rows[0].keys())
    pad = " " * indent
    header = pad + "| " + " | ".join(keys) + " |"
    sep = pad + "| " + " | ".join(["---"] * len(keys)) + " |"
    body_lines = []
    for row in rows:
        cells = []
        for k in keys:
            v = row.get(k, "")
            if isinstance(v, list):
                cells.append(", ".join(str(x) for x in v))
            elif isinstance(v, dict):
                cells.append(str(v))
            else:
                cells.append(str(v))
            # Markdown table 里不能有 | 或换行
            cells[-1] = cells[-1].replace("|", "\\|").replace("\n", " ")
        body_lines.append(pad + "| " + " | ".join(cells) + " |")
    return "\n".join([header, sep] + body_lines)


def render_registry(yaml_name: str, title: str, data: dict) -> str:
    """渲染单个注册表 YAML 为完整 Markdown。"""
    lines = [_header(title, yaml_name)]

    # version 行（如果存在）
    if "version" in data:
        lines.append(f"- YAML schema version: `{data['version']}`")
        lines.append("")

    # ── errors.yaml：application→1, protocol→2 带编号 ──
    if yaml_name == "errors.yaml":
        section_map = {"application": "1", "protocol": "2"}
        for key, value in data.items():
            if key == "version":
                continue
            num = section_map.get(key)
            heading = f"## {num}. {key.title()}" if num else f"## {key.title()}"
            lines.append(heading)
            lines.append("")
            if isinstance(value, list):
                lines.append(_render_table(value))
            elif isinstance(value, dict):
                lines.append(_render_dict(value))
            else:
                lines.append(str(value))
            lines.append("")
        return "\n".join(lines).rstrip() + "\n"

    # ── env.yaml：D{n}_* → D.{n} 带编号 ──
    if yaml_name == "env.yaml":
        groups = data.get("groups", {})
        lines.append("## 按 D 组")
        lines.append("")
        for gkey, gval in groups.items():
            # D1_env_and_keys → D.1
            num_match = re.match(r"D(\d+)", gkey)
            d_ref = f"D.{num_match.group(1)}" if num_match else gkey
            title = gval.get("title", gkey) if isinstance(gval, dict) else gkey
            lines.append(f"### {d_ref} {title}")
            lines.append("")
            if isinstance(gval, dict) and "vars" in gval:
                lines.append(_render_table(gval["vars"]))
                lines.append("")
        if "discipline" in data:
            lines.append("## Discipline")
            lines.append("")
            lines.append(_render_value(data["discipline"]))
            lines.append("")
        return "\n".join(lines).rstrip() + "\n"

    # ── known-red.yaml：问题与风险清单（按严重等级排序，量化口径 = baseline_failures） ──
    if yaml_name == "known-red.yaml":
        rules = data.get("rules") or []
        severity_order = {"P0": 0, "P1": 1, "P2": 2}
        lines.append("## 严重等级定义")
        lines.append("")
        lines.append(
            "| 等级 | 含义 | 处置 |\n"
            "|---|---|---|\n"
            "| P0 | 阻断：数据安全、数据正确性、合规证据失效 | 立即修复，不设基线豁免 |\n"
            "| P1 | 高：跨模块链路、契约/安全能力、运行期失败 | 当前以基线记账，按出口条件收敛 |\n"
            "| P2 | 中：局部质量、性能预算、体验 | 排期收敛，不得扩大 |"
        )
        lines.append("")
        lines.append("## 风险清单")
        lines.append("")
        lines.append(
            "> 量化口径：baseline_failures = 门禁实测失败数（0 即关闭，条目保留）。"
            "verify-docs.sh 对 baseline_failures 大于 0 的门禁降级 WARN。"
        )
        lines.append("")
        bt = chr(96)
        rows = []
        for rule in sorted(
            rules,
            key=lambda item: (severity_order.get(str(item.get("severity")), 9), str(item.get("rule_id"))),
        ):
            rows.append(
                {
                    "rule_id": bt + str(rule.get("rule_id", "")) + bt,
                    "severity": str(rule.get("severity", "")),
                    "impact_scope": "、".join(rule.get("impact_scope") or []),
                    "baseline_failures": rule.get("baseline_failures", 0),
                    "exit_condition": str(rule.get("exit_condition", "")),
                    "owner": str(rule.get("owner", "")),
                }
            )
        lines.append(_render_table(rows))
        lines.append("")
        return "\n".join(lines).rstrip() + "\n"

    # 按 key 顺序渲染；特殊处理 state-machines.yaml（14 个 domain 并列）
    if yaml_name == "state-machines.yaml":
        lines.append("## 通用规则")
        lines.append("")
        lines.append(
            "1. 状态值全小写 snake_case，英式拼写（`cancelled` 双 l）。\n"
            "2. 终态不可逆，除非显式定义恢复边。\n"
            "3. 迁移逻辑统一经领域常量表 + `CanTransitionTo`，状态列只由聚合根 `TransitionTo(newState)` 写入。\n"
            "4. 状态列统一 `status`，DDL 必有 `CHECK` 约束，约束名 `ck_{表名}_status`。\n"
            "5. 领域常量（`AllStates` + `CanTransitionTo`）、DDL CHECK、前端枚举、OpenAPI enum 均以本表为唯一口径生成或校验。"
        )
        lines.append("")
        lines.append("## 按域")
        lines.append("")

        for domain, entry in data.items():
            if domain == "version":
                continue
            if not isinstance(entry, dict):
                continue
            # domain 名字 → 中文标题映射（简单的）
            lines.append(f"### {domain}")
            lines.append("")

            meta = []
            for mk in ("table", "column", "check_constraint"):
                if mk in entry:
                    meta.append(f"- **{mk}**: `{entry[mk]}`")
            if meta:
                lines.extend(meta)
                lines.append("")

            # states 表格
            if "states" in entry and isinstance(entry["states"], list):
                states = entry["states"]
                terminal = set(entry.get("terminal", []))
                rows = []
                for s in states:
                    is_terminal = "🟥" if s in terminal else ""
                    rows.append({"state": s, "terminal": is_terminal})
                lines.append("**状态：**")
                lines.append("")
                lines.append(_render_table(rows))
                lines.append("")

            # transitions
            if "transitions" in entry and isinstance(entry["transitions"], dict):
                lines.append("**合法迁移：**")
                lines.append("")
                trans_rows = []
                for frm, tos in entry["transitions"].items():
                    trans_rows.append({"from": frm, "to": " → ".join(tos) if isinstance(tos, list) else str(tos)})
                lines.append(_render_table(trans_rows))
                lines.append("")

            # discipline / note / terminal
            for extra in ("discipline", "terminal", "model", "rotation", "introspection",
                          "transaction_type", "transaction_note", "device_flow"):
                if extra in entry and entry[extra]:
                    lines.append(f"**{extra}:** {entry[extra]}")
                    lines.append("")

        return "\n".join(lines)

    # 通用处理：按 key 顺序渲染
    for key, value in data.items():
        if key == "version":
            continue
        lines.append(f"## {key.replace('_', ' ').title()}")
        lines.append("")

        if isinstance(value, list):
            if value and isinstance(value[0], dict):
                # 判断是否所有 dict 都只有一个 key → 用项目符号更紧凑
                all_single_key = all(len(item) == 1 for item in value)
                if all_single_key:
                    for item in value:
                        k, v = next(iter(item.items()))
                        lines.append(f"- **{k}**: {_render_value(v)}")
                else:
                    rows = value
                    if yaml_name == "provider-kinds.yaml":
                        # managed_via/consumer_table are omitted for kinds owned
                        # by the unified registry, so rows have different keys.
                        # Render the union; otherwise the first row decides the
                        # columns and the delegated fields disappear.
                        columns: list[str] = []
                        for item in value:
                            for column in item:
                                if column not in columns:
                                    columns.append(column)
                        rows = [
                            {column: item.get(column, "") for column in columns}
                            for item in value
                        ]
                    lines.append(_render_table(rows))
            else:
                lines.append(_render_value(value))
        elif isinstance(value, dict):
            lines.append(_render_dict(value))
        else:
            lines.append(str(value))
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="零差异门禁模式")
    parser.add_argument("--only", default=None, help="只处理某个注册表（如 naming、state-machines）")
    args = parser.parse_args()

    targets = {}
    for yaml_name, (md_name, title) in REGISTRY_MAP.items():
        if args.only and args.only not in yaml_name and args.only not in md_name:
            continue
        yaml_path = YAML_DIR / yaml_name
        md_path = MD_DIR / md_name
        targets[yaml_path] = (md_path, title, yaml_name)

    if not targets:
        print(f"ERROR: 没找到 --only {args.only} 对应的注册表")
        sys.exit(2)

    diff_count = 0

    for yaml_path, (md_path, title, yaml_name) in targets.items():
        if not yaml_path.exists():
            print(f"  SKIP {yaml_name} (YAML 不存在)")
            continue

        data = yaml.safe_load(open(yaml_path)) or {}
        content = render_registry(yaml_name, title, data)

        if args.check:
            if not md_path.exists():
                print(f"  NEW  {md_path.name} (需生成)")
                diff_count += 1
            elif md_path.read_text().strip() != content.strip():
                print(f"  DIFF {md_path.name}")
                diff_count += 1
            else:
                print(f"  OK   {md_path.name}")
        else:
            md_path.write_text(content)
            print(f"  GEN  {md_path.name}")

    print()
    if args.check:
        if diff_count:
            print(f"FAIL: {diff_count} 个注册表 md 需要重新生成")
            sys.exit(1)
        print(f"PASS: 全部 {len(targets)} 个注册表渲染层零差异")
    else:
        print(f"完成：生成 {len(targets)} 个 Markdown 渲染层")


if __name__ == "__main__":
    main()
