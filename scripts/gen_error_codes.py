#!/usr/bin/env python3
"""gen_error_codes.py — 从 errors.yaml 生成前端错误码 TS 类型

唯一事实源：contracts/registries/errors.yaml
生成物：web/src/generated/error-codes.ts

Go 端错误码已手写于 internal/platform/errors/errors.go，
一致性由 check-registry-sync.py（check_error_codes）保证。
本脚本仅负责前端 TS 联合类型 + HTTP 状态码映射。

Usage:
  python3 scripts/gen_error_codes.py           # 生成
  python3 scripts/gen_error_codes.py --check   # 零差异门禁

输入：contracts/registries/errors.yaml
输出：web/src/generated/error-codes.ts；--check 模式 diff 并输出 PASS/FAIL
--check 行为：--check 模式比较当前 error-codes.ts 与生成结果的差异，无差异时 PASS
消费方：check-generated-zero-diff.sh、CI
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

import yaml  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
REGISTRY_PATH = ROOT / "contracts/registries/errors.yaml"
TS_OUTPUT = ROOT / "web/src/generated/error-codes.ts"


def _oxfmt(text: str, rel_path: str) -> str:
    """把渲染出的 TS 交给 oxfmt，使生成物本身就是 `pnpm run format:check` 的结果。

    生成物若不自带格式，`pnpm run format` 与「重新生成」会互相推翻（web 的格式
    门禁覆盖仓库全部 TS，不区分手写与生成）。`--stdin-filepath` 让 oxfmt 只按该
    路径推断解析器，结果写到 stdout。
    """
    oxfmt = ROOT / "web" / "node_modules" / ".bin" / "oxfmt"
    if not oxfmt.exists():
        raise RuntimeError("未找到 oxfmt：请先在 web/ 下执行 pnpm install")
    rel_in_web = rel_path[len("web/") :] if rel_path.startswith("web/") else rel_path
    try:
        proc = subprocess.run(
            [str(oxfmt), "-c", "oxfmt.json", f"--stdin-filepath={rel_in_web}"],
            input=text,
            capture_output=True,
            text=True,
            check=False,
            cwd=ROOT / "web",
        )
    except FileNotFoundError as exc:
        raise RuntimeError("未找到 oxfmt：请先在 web/ 下执行 pnpm install") from exc
    if proc.returncode != 0:
        raise RuntimeError(f"oxfmt 失败：{proc.stderr.strip()}")
    return proc.stdout


def _load():
    data = yaml.safe_load(open(REGISTRY_PATH)) or {}
    return data


def _render_ts(data: dict) -> str:
    app_codes = data.get("application", []) or []
    proto_codes = data.get("protocol", []) or []

    lines = []
    lines.append("// Code generated by scripts/gen_error_codes.py. DO NOT EDIT.")
    lines.append("// Source: contracts/registries/errors.yaml")
    lines.append("// 前端仅消费应用层错误码（ErrorResponse.error.code）。")
    lines.append("// 协议面错误码（OAuth/SCIM）由协议客户端按 RFC 独立处理。")
    lines.append("")
    lines.append("/** 应用层错误码联合类型。 */")
    if app_codes:
        union = " | ".join(f'"{e["code"]}"' for e in app_codes)
        lines.append(f"export type AppErrorCode = {union};")
    else:
        lines.append("export type AppErrorCode = string;")
    lines.append("")
    lines.append("/** OAuth 2.1 / OIDC 协议错误码（RFC 6749 / 6750）。 */")
    oauth_codes = [e["code"] for e in proto_codes if e.get("namespace") != "scim"]
    if oauth_codes:
        union = " | ".join(f'"{c}"' for c in oauth_codes)
        lines.append(f"export type OAuthErrorCode = {union};")
    else:
        lines.append("export type OAuthErrorCode = string;")
    lines.append("")
    lines.append("/** SCIM 2.0 协议错误码（RFC 7644）。 */")
    scim_codes = [e["code"] for e in proto_codes if e.get("namespace") == "scim"]
    if scim_codes:
        union = " | ".join(f'"{c}"' for c in scim_codes)
        lines.append(f"export type ScimErrorCode = {union};")
    else:
        lines.append("export type ScimErrorCode = string;")
    lines.append("")
    lines.append("/** 错误码 → HTTP 状态码映射（仅应用层）。 */")
    lines.append("export const ERROR_CODE_HTTP: Record<AppErrorCode, number> = {")
    for entry in app_codes:
        code = entry.get("code", "")
        http = entry.get("http", 0)
        lines.append(f'  "{code}": {http},')
    lines.append("};")
    return _oxfmt("\n".join(lines) + "\n", "web/src/generated/error-codes.ts")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="检查模式")
    args = parser.parse_args()

    data = _load()
    ts_content = _render_ts(data)

    if args.check:
        if not TS_OUTPUT.exists():
            print(f"  NEW  {TS_OUTPUT.relative_to(ROOT)}")
            print("FAIL: 需要重新生成")
            sys.exit(1)
        if TS_OUTPUT.read_text().strip() != ts_content.strip():
            print(f"  DIFF {TS_OUTPUT.relative_to(ROOT)}")
            print("FAIL: 与注册表不一致")
            sys.exit(1)
        print(f"  OK   {TS_OUTPUT.relative_to(ROOT)}")
        print("PASS: 生成物零差异")
        return

    TS_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    TS_OUTPUT.write_text(ts_content)
    print(f"GEN  {TS_OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
