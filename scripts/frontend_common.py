"""控制台事实源的共享解析器（路由表 / 菜单 / 页面文件）。

`router.tsx` 与 `menu.tsx` 是「哪些页面存在」这一事实的源文件，任何脚本都不应
用各自的临时正则去猜。这里只放**唯一**一份解析实现，供
`check-frontend-coverage.py` 与 `gen_frontend_registry.py` 共用，避免两份解析器
对同一份源码给出不同答案（那正是本项目此前出现文档与代码漂移的成因）。

输入：web/src/app/router/router.tsx、web/src/features/navigation/menu.tsx、web/src/pages/、docs/design/frontend/registry.md
输出：暴露 Router/Menu/Design 三张表（供 check-frontend-coverage.py 与 gen_frontend_registry.py 共用）
--check 行为：无 --check；库模块
消费方：被 check-frontend-coverage.py 与 gen_frontend_registry.py import；不纳入 verify-docs.sh
"""

