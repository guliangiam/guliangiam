def split_objects(text: str) -> list[str]:
    """Split a JS array body into its top-level `{...}` object sources.

    `router.tsx` nests `children: [...]` inside the AppShell route, so a regex
    over `path:` cannot tell a top-level route from a child -- and the child
    paths are relative (`"users"` under `path: "/"`), which is exactly the
    resolution this parser has to reproduce.
    """
    objects: list[str] = []
    depth = 0
    start = None
    quote = ""
    index = 0
    while index < len(text):
        char = text[index]
        if quote:
            if char == "\\":
                index += 2
                continue
            if char == quote:
                quote = ""
        elif char in "\"'`":
            quote = char
        elif char == "{":
            if depth == 0:
                start = index
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0 and start is not None:
                objects.append(text[start : index + 1])
        index += 1
    return objects


def _imports(source: str) -> list[tuple[str, str]]:
    """Return (imported name, specifier) pairs, including multi-name braces.

    The previous single-name regex missed `import { withSuspense, RouterErrorElement }`,
    so legitimate element targets looked unimported.
    """
    pairs: list[tuple[str, str]] = []
    pattern = r'import\s+(?:type\s+)?([^;]*?)\s+from\s+["\']([^"\']+)["\']'
    for clause, spec in re.findall(pattern, source, re.DOTALL):
        brace = re.search(r"\{([^}]*)\}", clause)
        if brace:
            for item in brace.group(1).split(","):
                name = item.strip()
                if name:
                    pairs.append((name.split(" as ")[-1].strip(), spec))
            head = clause[: brace.start()].strip().rstrip(",").strip()
        else:
            head = clause.strip().split(",")[0].strip()
        if head and not head.startswith("*"):
            pairs.append((head, spec))
    return pairs


def _extract_array(source: str, open_index: int) -> str:
    """Return the body between the `[` at `open_index` and its matching `]`."""
    depth = 0
    start = open_index + 1
    quote = ""
    index = open_index
    while index < len(source):
        char = source[index]
        if quote:
            if char == "\\":
                index += 2
                continue
            if char == quote:
                quote = ""
        elif char in ('"', "'", chr(96)):
            quote = char
        elif char == "[":
            if depth == 0:
                start = index + 1
            depth += 1
        elif char == "]":
            depth -= 1
            if depth == 0:
                return source[start:index]
        index += 1
    return ""


def _top_level_spreads(body: str) -> list[str]:
    """Return spread names (three dots + identifier) at the array's own depth.

    split_objects() only yields brace objects, so a top-level spread such as
    authRoutes never reaches the object loop -- those routes were dropped and
    their pages were reported unreachable.
    """
    names: list[str] = []
    depth = 0
    quote = ""
    index = 0
    while index < len(body):
        char = body[index]
        if quote:
            if char == "\\":
                index += 2
                continue
            if char == quote:
                quote = ""
        elif char in ('"', "'", chr(96)):
            quote = char
        elif char in "[{":
            depth += 1
        elif char in "]}":
            depth -= 1
        elif depth == 0 and body.startswith("...", index):
            match = re.match(r"\.\.\.(\w+)", body[index:])
            if match:
                names.append(match.group(1))
                index += match.end()
                continue
        index += 1
    return names


def _module_path(spec: str) -> Path | None:
    """Resolve a relative import specifier against the router directory."""
    base = (ROUTER.parent / spec).resolve()
    for candidate in (
        base.with_suffix(".tsx"),
        base.with_suffix(".ts"),
        base / "index.tsx",
        base / "index.ts",
    ):
        if candidate.is_file():
            return candidate.resolve()
    return None


def _route_sources() -> list[Path]:
    """`router.tsx` plus every local router module it imports, transitively."""
    seen: set[Path] = set()
    pending = [ROUTER]
    while pending:
        path = pending.pop()
        if path in seen or not path.is_file():
            continue
        seen.add(path)
        for _name, spec in _imports(path.read_text(encoding="utf-8")):
            if spec.startswith("./") or spec.startswith("../"):
                target = _module_path(spec)
                if target is not None and target.parent == ROUTER.parent.resolve():
                    pending.append(target)
    return sorted(seen)


def _collect_routes(
    body: str,
    base: str,
    routes: dict[str, str],
    arrays: dict[str, tuple[str, int]],
    seen_arrays: set[str],
) -> None:
    """Record routes from a route-array body, recursing into children and spreads."""
    for obj in split_objects(body):
        path_match = re.search(r'path:\s*"([^"]*)"', obj)
        element = re.search(r"<(\w+)[\s/>]", obj)
        children = re.search(r"children:\s*\[", obj)
        current = base
        if path_match:
            suffix = path_match.group(1)
            if suffix == "*":
                current = "*"
            elif suffix.startswith("/"):
                current = suffix
            else:
                current = f"{base.rstrip('/')}/{suffix}"
            if element:
                routes[current] = element.group(1)
        elif element and base:
            routes[base] = element.group(1)  # `index: true`
        if children:
            child_body = _extract_array(obj, obj.index("[", children.start()))
            _collect_routes(child_body, current, routes, arrays, seen_arrays)
            continue
        for name in re.findall(r"\.\.\.(\w+)", obj):
            if name in arrays and name not in seen_arrays:
                seen_arrays.add(name)
                text, index = arrays[name]
                _collect_routes(_extract_array(text, index), current, routes, arrays, seen_arrays)


def parse_router() -> tuple[dict[str, str], dict[str, str], dict[str, str], set[str]]:
    """Return routes, lazy imports, static imports and locally declared components.

    The router entry aggregates per-domain modules (`auth-routes.tsx`,
    `identity-routes.tsx`, ...). Reading only `router.tsx` reported a single
    route, so every page looked unreachable and the coverage gate produced 270
    false failures. Imports are followed transitively, so adding a domain module
    never requires a parser change.
    """
    sources = _route_sources()
    texts = [path.read_text(encoding="utf-8") for path in sources]

    lazy_imports: dict[str, str] = {}
    static_imports: dict[str, str] = {}
    local_components: set[str] = set()
    arrays: dict[str, tuple[str, int]] = {}
    for text in texts:
        # `lazy` declarations are wrapped by the formatter, so the arrow body may
        # sit on any line -- a single-line regex silently drops those components
        # and reports "not imported" for pages that are in fact wired.
        lazy_imports.update(
            {
                name: target
                for name, target in re.findall(
                    r'const\s+(\w+)\s*=\s*lazy\(\s*\(\)\s*=>\s*import\("([^"]+)"\)\s*,?\s*\)',
                    text,
                    re.DOTALL,
                )
            }
        )
        for name, spec in _imports(text):
            static_imports.setdefault(name, spec)
        local_components.update(re.findall(r"^(?:function|class|const)\s+([A-Z]\w*)", text, re.MULTILINE))
        for match in re.finditer(r"export\s+const\s+(\w+)\s*(?::[^=]*?)?=\s*\[", text):
            arrays.setdefault(match.group(1), (text, match.end() - 1))

    entry = ROUTER.read_text(encoding="utf-8")
    routes: dict[str, str] = {}
    # Base path each spread module is mounted under: a module spread into a layout
    # route's children is relative to that route, a top-level spread is absolute.
    bases: dict[str, str] = {}
    start = entry.index("createBrowserRouter(")
    body = _extract_array(entry, entry.index("[", start))
    for obj in split_objects(body):
        path_match = re.search(r'path:\s*"([^"]*)"', obj)
        element = re.search(r"<(\w+)[\s/>]", obj)
        children = re.search(r"children:\s*\[", obj)
        if not children:
            if path_match and element:
                routes[path_match.group(1)] = element.group(1)
            continue
        base = path_match.group(1) if path_match else ""
        if path_match and element:
            routes[base] = element.group(1)
        child_body = _extract_array(obj, obj.index("[", children.start()))
        for name in _top_level_spreads(child_body):
            bases[name] = base
        _collect_routes(child_body, base, routes, arrays, set())

    for name in _top_level_spreads(body):
        bases.setdefault(name, "")

    seen_arrays = set(bases)
    for name, base in bases.items():
        if name in arrays:
            text, index = arrays[name]
            _collect_routes(_extract_array(text, index), base, routes, arrays, seen_arrays)

    return routes, lazy_imports, static_imports, local_components


def parse_menu() -> tuple[dict[str, list[str]], dict[str, set[str]], dict[str, set[str]]]:
    """Return ({group key: routeKeys}, {group key: child keys}, {group key: child labels})."""
    source = MENU.read_text(encoding="utf-8")
    start = source.index("export const menuGroups")
    body = source[start:]
    # The next top-level export ends the array; menu.tsx keeps helpers after it.
    end = body.find("\nexport ", 1)
    if end != -1:
        body = body[:end]

    groups: list[tuple[str, str]] = []  # (key, slice start)
    for match in re.finditer(r'\n\s*\{\s*\n\s*key:\s*"(\w+)",\s*\n\s*label:\s*"([^"]+)"', body):
        groups.append((match.group(1), match.start()))

    route_keys: dict[str, list[str]] = {}
    children: dict[str, set[str]] = {}
    labels: dict[str, set[str]] = {}
    for index, (key, offset) in enumerate(groups):
        stop = groups[index + 1][1] if index + 1 < len(groups) else len(body)
        block = body[offset:stop]
        rk = re.search(r"routeKeys:\s*\[([^\]]*)\]", block)
        route_keys[key] = (
            [item.strip().strip('"') for item in rk.group(1).split(",") if item.strip()] if rk else []
        )
        children[key] = {item for item in re.findall(r'key:\s*"(/[^"]*)"', block)}
        labels[key] = {item for item in re.findall(r'label:\s*"(nav\.[^"]*)"', block)}
    return route_keys, children, labels


def resolve_module(target: str) -> Path | None:
    """Resolve an `@/...` specifier the way Vite does, without a bundler."""
    base = ROOT / "web/src" / target.removeprefix("@/")
    for candidate in (
        base,
        base.with_suffix(".tsx"),
        base.with_suffix(".ts"),
        base / "index.tsx",
        base / "index.ts",
    ):
        if candidate.is_file():
            return candidate.resolve()
    return None
