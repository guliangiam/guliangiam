#!/usr/bin/env python3

"""从 env.yaml 生成仓库根目录 .env.example

输入：contracts/registries/env.yaml
输出：.env.example；--check 模式 diff 并输出 PASS/FAIL
--check 行为：--check 模式比较当前 .env.example 与生成结果的差异，无差异时 PASS
消费方：check-generated-zero-diff.sh、CI"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
REGISTRY_PATH = ROOT / "contracts/registries/env.yaml"
DOT_ENV_OUTPUT = ROOT / ".env.example"
DEPLOYMENT_MD = ROOT / "docs/operations/deployment.md"

# 分组标题映射：D{n}_* → D.{n}
_GROUP_NUM_RE = re.compile(r"D(\d+)")

# 占位值生成规则
_PLACEHOLDER_DEFAULTS = {
    "true": "true",
    "false": "false",
    "postgresql": "postgres://guliangiam:guliangiam@localhost:5432/guliangiam?sslmode=disable",
    "mysql": "mysql://guliangiam:guliangiam@localhost:3306/guliangiam",
    "": "",
}


def _placeholder(var: dict) -> str:
    """根据 YAML 字段推断 .env.example 的占位值。

    规则优先级：
      1. var.default → 直接用
      2. var.values 存在且只有一个 → 用该值
      3. var.values 存在且含常见值（postgresql/mysql/local/false/true）→ 取首项
      4. 密钥类变量（KEY/SECRET/HMAC/TOKEN/PASSWORD）→ 留空注释提示
      5. 其他 → 留空，不填假值
    """
    if "default" in var and var["default"] is not None:
        d = str(var["default"])
        # 布尔字符串保持原样
        return d

    values = var.get("values")
    name = var.get("name", "")

    if values and isinstance(values, list):
        candidates = ["true", "false", "postgres", "mysql", "local", "redis", "memory"]
        for c in candidates:
            if c in values:
                return c
        return str(values[0])  # 取第一个候选值

    # 密钥类 → 留空注释，不填假值
    key_keywords = ("KEY", "SECRET", "HMAC", "TOKEN", "PASSWORD", "CREDENTIAL")
    if any(k in name.upper() for k in key_keywords):
        return ""

    # 端口 / 地址类 → 常见默认
    if name.endswith("_PORT"):
        return "8000"
    if name.endswith("_ADDR"):
        return ":8000"
    if name.endswith("_DSN") or name.endswith("_URL"):
        return ""

    return ""


def _commented(var: dict) -> bool:
    """该变量在 .env.example 中是否应该默认注释掉。

    - deprecated=True → 注释掉
    - required=false + 有 default（且不是关键路径）→ 默认展开但不强制
    - required=false + 无 default → 注释掉（让部署方按需填写）
    """
    if var.get("deprecated"):
        return True
    req = var.get("required", False)
    if req is False:
        # required=false 且有 default 的变量也展开（作为默认配置展示）
        # 但前端构建变量（VITE_）注释掉（不在后端 .env.example 活跃组）
        if var.get("name", "").startswith("VITE_"):
            return True
        return False  # 有 default 也展示
    return False  # required=true 或 "production" → 展开


def _format_line(var: dict) -> str:
    """生成单行 KEY=value # description。"""
    name = var["name"]
    desc = var.get("description", "")
    note = var.get("note", "")
    deprecated = var.get("deprecated", False)

    parts = [desc]
    if deprecated:
        parts.insert(0, "[已废弃]")
    if note:
        parts.append(f"（{note}）")
    comment = " ".join(p for p in parts if p).strip()

    value = _placeholder(var)
    line = f"{name}={value}"
    if comment:
        line += f"  # {comment}"
    return line


def _render(data: dict) -> str:
    """渲染完整 .env.example 文本。"""
    groups = data.get("groups", {})
    discipline = data.get("discipline", [])

    lines: list[str] = []
    lines.append("# ============================================================")
    lines.append("# GuliangIAM Environment Variables")
    lines.append("# Copy this file to .env.local (preferred) or .env and fill in your values.")
    lines.append("# NEVER commit real secrets to version control.")
    lines.append("# Auto-generated by scripts/gen_env_vars.py — DO NOT EDIT MANUALLY")
    lines.append(f"# Source: contracts/registries/env.yaml")
    lines.append("# ============================================================")
    lines.append("")

    total_vars = 0
    total_groups = 0

    for gkey, gval in groups.items():
        if not isinstance(gval, dict) or "vars" not in gval:
            continue

        num_match = _GROUP_NUM_RE.match(gkey)
        d_ref = f"D.{num_match.group(1)}" if num_match else gkey
        title = gval.get("title", gkey)

        # 节头
        lines.append(f"# === {d_ref} {title} ===")
        total_groups += 1

        # 小节注释（从 discipline 提取相关条目）
        for rule in discipline:
            rule_str = str(rule)
            if any(kw in rule_str for kw in (d_ref.split(".")[0], title.split()[0] if title else "")):
                lines.append(f"# 纪律: {rule_str}")

        # 变量
        for var in gval["vars"]:
            total_vars += 1
            line = _format_line(var)
            if _commented(var):
                line = "# " + line
            lines.append(line)

        lines.append("")

    # 纪律/红线
    if discipline:
        lines.append("# === Discipline & Red Lines ===")
        for rule in discipline:
            lines.append(f"# - {rule}")
        lines.append("")

    lines.append(f"# Generated {total_vars} variables across {total_groups} groups.")
    lines.append("")

    return "\n".join(lines)


def _load() -> dict:
    """加载 env.yaml。"""
    if not REGISTRY_PATH.exists():
        print(f"ERROR: 注册表不存在: {REGISTRY_PATH}")
        sys.exit(2)
    return yaml.safe_load(REGISTRY_PATH.read_text()) or {}


def main():
    parser = argparse.ArgumentParser(description="从 env.yaml 生成 .env.example")
    parser.add_argument("--check", action="store_true", help="零差异门禁")
    parser.add_argument("--check-doc", action="store_true", help="同时检查 deployment.md 中是否引用了所有 D 组")
    args = parser.parse_args()

    data = _load()
    content = _render(data)

    if args.check:
        # 1. 检查 .env.example 是否存在且零差异
        if not DOT_ENV_OUTPUT.exists():
            print(f"  NEW  .env.example (需生成)")
            print("FAIL: 需要运行 python3 scripts/gen_env_vars.py")
            sys.exit(1)

        existing = DOT_ENV_OUTPUT.read_text()
        if existing.strip() != content.strip():
            print(f"  DIFF .env.example")
            # 显示 diff 摘要
            import difflib
            diff = list(difflib.unified_diff(
                existing.splitlines(), content.splitlines(),
                fromfile="existing .env.example", tofile="generated",
                lineterm=""
            ))
            for line in diff[:20]:
                print(f"    {line}")
            if len(diff) > 20:
                print(f"    ... (+{len(diff) - 20} more lines)")
            print("FAIL: .env.example 与 env.yaml 不一致 — 运行 python3 scripts/gen_env_vars.py")
            sys.exit(1)

        print(f"  OK   .env.example ({DOT_ENV_OUTPUT.relative_to(ROOT)})")

        # 2. 检查 docs/operations/deployment.md 是否引用了所有 D 组
        if args.check_doc and DEPLOYMENT_MD.exists():
            md_text = DEPLOYMENT_MD.read_text()
            missing_refs = []
            for gkey in data.get("groups", {}):
                num_match = _GROUP_NUM_RE.match(gkey)
                if num_match:
                    d_ref = f"D.{num_match.group(1)}"
                    if d_ref not in md_text and "env-var-registry" not in md_text.lower():
                        missing_refs.append(d_ref)
            if missing_refs:
                print(f"  WARN: deployment.md 可能未引用 {missing_refs}")
            else:
                print(f"  OK   deployment.md 引用覆盖正常")

        print("PASS: .env.example 与 env.yaml 零差异")
        return

    # 正常生成
    DOT_ENV_OUTPUT.write_text(content)
    print(f"GEN  {DOT_ENV_OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
