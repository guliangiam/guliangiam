#!/usr/bin/env python3
"""CI benchmark regression gate — cross-platform (macOS/Linux).

输入：go test -bench=. -benchmem 输出文本；baseline 文件 scripts/bench-baseline.txt
输出：PASS/FAIL + 回归 benchmark 列表与当前 ns/op
--check 行为：--check 模式仅校验无回归、不更新 baseline
消费方：独立脚本（bench-gate.sh 薄包装）、CI
"""
import os, re, sys, subprocess, argparse

def extract_ns(line):
    m = re.search(r'(\d+(?:\.\d+)?)\s+(ns|µs|ms)/op', line)
    if not m: return None
    val, unit = float(m.group(1)), m.group(2)
    if unit == 'ns': return val
    if unit == 'µs': return val * 1000
    if unit == 'ms': return val * 1_000_000
    return None

def extract_name(line):
    return re.sub(r'-\d+$', '', line.split()[0])

def parse_go_output(text):
    result = {}
    for line in text.splitlines():
        if not line.startswith('Benchmark'): continue
        name = extract_name(line)
        ns = extract_ns(line)
        if name and ns is not None: result[name] = ns
    return result

def parse_baseline(path):
    result = {}
    if not os.path.exists(path):
        print(f"ERROR: baseline not found: {path}")
        print("Generate it with: scripts/bench-gate.sh --generate")
        sys.exit(3)
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#'): continue
            name = extract_name(line)
            ns = extract_ns(line)
            if name and ns is not None: result[name] = ns
    return result

BENCH_RE_FULL = r'Benchmark(Session|Enforce|JWT|HashToken|FieldEncryption|UUIDv7)'
BENCH_RE_CI   = r'Benchmark(SessionLookup|Enforce_E2E|JWT(Issue|Validate))'

def run_bench(repo_root, bench_re, benchtime):
    cmd = ['go', 'test', f'-bench={bench_re}', f'-benchtime={benchtime}',
           '-benchmem', '-run=^$', './internal/...']
    print(f"Running: {' '.join(cmd)}")
    result = subprocess.run(cmd, capture_output=True, text=True, cwd=repo_root)
    if result.returncode != 0:
        print("ERROR: benchmark run failed!")
        print(result.stderr[-2000:])
        sys.exit(2)
    return result.stdout

def generate_baseline(repo_root, baseline_path):
    benchtime = '1500ms'
    print(f"=== Generating baseline (benchtime={benchtime}) ===\n")
    stdout = run_bench(repo_root, BENCH_RE_FULL, benchtime)
    with open(baseline_path, 'w') as f:
        f.write("# Benchmark baseline — auto-generated by scripts/bench-gate.sh --generate\n")
        f.write("# Benchtime: 1500ms (stabilization run — less noise than 300ms)\n")
        f.write("# Regenerate: bash scripts/bench-gate.sh --generate\n")
        f.write("# Format matches `go test -benchmem` output exactly\n")
        f.write("\n")
        for line in stdout.splitlines():
            if line.startswith('Benchmark'):
                f.write(line + "\n")
    print(f"\n✅ Baseline written: {baseline_path}")

def main():
    parser = argparse.ArgumentParser(description='CI benchmark regression gate')
    parser.add_argument('--threshold', type=float, default=10.0,
                        help='Allowed regression %% (default 10%% — 规范 8.7 same-host/Go-version budget)')
    parser.add_argument('--benchtime', default='300ms',
                        help='go test -benchtime (default 300ms for gate; 1500ms for baseline gen)')
    parser.add_argument('--ci', action='store_true',
                        help='CI/PR gate — only hot paths, benchtime=100ms')
    parser.add_argument('--generate', action='store_true',
                        help='Regenerate bench-baseline.txt (benchtime=1500ms — stabilized)')
    args = parser.parse_args()

    threshold = args.threshold
    benchtime = args.benchtime
    script_dir = os.path.dirname(os.path.abspath(__file__))
    repo_root = os.path.dirname(script_dir)
    baseline_path = os.path.join(script_dir, 'bench-baseline.txt')

    if args.generate:
        generate_baseline(repo_root, baseline_path)
        return

    baseline = parse_baseline(baseline_path)

    if args.ci:
        bench_re = BENCH_RE_CI
        benchtime = '100ms'
        print(f"=== bench-gate (CI mode, threshold={threshold}%, benchtime={benchtime}) ===\n")
    else:
        bench_re = BENCH_RE_FULL
        print(f"=== bench-gate (full mode, threshold={threshold}%, benchtime={benchtime}) ===\n")

    stdout = run_bench(repo_root, bench_re, benchtime)
    current = parse_go_output(stdout)

    regressions, improved, checked = [], 0, 0
    header = f"{'Benchmark':<42} {'Baseline':>12} {'Current':>12} {'Delta':>10} Status"
    print()
    print(header)
    print('-' * len(header))

    for name in sorted(baseline.keys()):
        if name not in current: continue
        b, c = baseline[name], current[name]
        checked += 1
        delta = ((c - b) / b * 100) if b > 0 else 0
        if delta > threshold:
            status = "REGRESSED !! "
            regressions.append((name, b, c, delta))
        elif delta < -5:
            status = "IMPROVED ✓"
            improved += 1
        else:
            status = "OK"
        print(f"{name:<42} {b:>10.1f} ns {c:>10.1f} ns {delta:>+9.1f}% {status}")

    print()
    print("-" * 72)
    print(f"Checked:   {checked} benchmark(s) against baseline")
    print(f"Improved:  {improved}")
    print(f"Regressed (>{threshold}%): {len(regressions)}")

    if regressions:
        print()
        print("!! PERFORMANCE REGRESSION DETECTED")
        print()
        for name, b, c, d in regressions:
            print(f"  - {name}: {b:.1f}ns -> {c:.1f}ns (+{d:.1f}%)")
        print()
        print("Remediation:")
        print("  1. Debug: go test -bench='...' -benchtime=1s -benchmem -run=^$ ./...")
        print("  2. Update baseline (if intentional): bash scripts/bench-gate.sh --generate")
        sys.exit(1)

    print()
    print(f"OK: All benchmarks within {threshold}% threshold")

if __name__ == '__main__':
    main()
