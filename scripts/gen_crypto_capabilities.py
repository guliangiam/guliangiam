#!/usr/bin/env python3
"""gen_crypto_capabilities.py — 从 crypto.yaml 生成能力位常量与清单

唯一事实源：contracts/registries/crypto.yaml
生成物：internal/platform/crypto/capabilities_gen.go（禁止手改）

只生成「数据」：能力位 ID 常量、YAML 声明顺序、failure_mode 派生清单。
探测实现（probeXxx）与分派表（capabilityDetectors）必须手写在 suite.go；
capabilities_test.go 断言生成物与分派表双向完备，防止「注册表加了能力位
但忘记写探测」。

Usage:
  python3 scripts/gen_crypto_capabilities.py           # 生成
  python3 scripts/gen_crypto_capabilities.py --check    # 零差异校验（不写盘，差异即非零退出）

输入：contracts/registries/crypto.yaml
输出：internal/platform/crypto/capabilities_gen.go
--check 行为：比较生成物与声明，无差异 PASS；缺失或漂移非零退出
消费方：check-generated-zero-diff.sh、check-registry-sync.py、CI
"""
from __future__ import annotations

import argparse
import difflib
import re
import subprocess
import sys
from pathlib import Path

import yaml  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
REGISTRY_PATH = ROOT / "contracts/registries/crypto.yaml"
OUTPUT_PATH = ROOT / "internal/platform/crypto/capabilities_gen.go"

GENERATED_HEADER = (
    "// Code generated by scripts/gen_crypto_capabilities.py from "
    "contracts/registries/crypto.yaml; DO NOT EDIT."
)

FAILURE_MODES = {"refuse", "degrade"}
CAPABILITY_ID_PATTERN = re.compile(r"^[a-z][a-z0-9_]*$")

# Go 标识符里的首字母缩写：只影响常量命名，不承载任何能力位语义。
_INITIALISMS = {
    "api", "ca", "gcm", "gm", "https", "http", "id", "ip",
    "jwt", "sm2", "sm3", "sm4", "tls", "url",
}


def _gofmt(text: str) -> str:
    """把渲染出的 Go 源码交给 gofmt，使生成物本身就是 gofmt 结果。"""
    try:
        proc = subprocess.run(
            ["gofmt"], input=text, capture_output=True, text=True, check=False
        )
    except FileNotFoundError as exc:
        raise RuntimeError(
            "未找到 gofmt：生成物必须等于 gofmt 输出，请安装 Go 工具链"
        ) from exc
    if proc.returncode != 0:
        raise RuntimeError(f"gofmt 失败：{proc.stderr.strip()}")
    return proc.stdout


def _const_name(capability_id: str) -> str:
    """能力位 ID → Go 常量名（sm2_sign → CapabilitySM2Sign）。"""
    parts = re.split(r"[_-]+", capability_id)
    body = "".join(
        part.upper()
        if part.lower() in _INITIALISMS or re.match(r"^(sm|gm)\d+$", part.lower())
        else part[:1].upper() + part[1:]
        for part in parts
        if part
    )
    return f"Capability{body}"


def _error(message: str) -> None:
    print(f"ERROR: {message}")
    sys.exit(1)


def _load_capabilities() -> list[dict]:
    """读取并校验 crypto.yaml 的能力位声明，返回 YAML 声明顺序。"""
    if not REGISTRY_PATH.exists():
        _error(f"{REGISTRY_PATH} 不存在")

    data = yaml.safe_load(REGISTRY_PATH.read_text()) or {}
    capabilities = data.get("capabilities")
    if not isinstance(capabilities, list) or not capabilities:
        _error("crypto.yaml capabilities 缺失或为空")

    seen_ids: set[str] = set()
    seen_constants: dict[str, str] = {}
    for index, entry in enumerate(capabilities):
        if not isinstance(entry, dict):
            _error(f"capabilities[{index}] 不是映射")
        capability_id = entry.get("id")
        if not isinstance(capability_id, str) or not CAPABILITY_ID_PATTERN.match(capability_id):
            _error(f"capabilities[{index}] id 缺失或非法: {capability_id!r}")
        if capability_id in seen_ids:
            _error(f"crypto.yaml 能力位 ID 重复: {capability_id}")
        seen_ids.add(capability_id)

        failure_mode = entry.get("failure_mode")
        if failure_mode not in FAILURE_MODES:
            _error(
                f"crypto.yaml 能力位 {capability_id} failure_mode={failure_mode!r}，"
                f"合法值: {sorted(FAILURE_MODES)}"
            )

        constant = _const_name(capability_id)
        if constant in seen_constants:
            _error(
                f"能力位 ID {capability_id} 与 {seen_constants[constant]} "
                f"映射到同一 Go 常量名 {constant}"
            )
        seen_constants[constant] = capability_id
    return capabilities


def _render_go(capabilities: list[dict]) -> str:
    """渲染 capabilities_gen.go：只含常量与清单，不含任何探测实现。"""
    def ids_of(mode: str) -> list[str]:
        return [
            entry["id"] for entry in capabilities if entry["failure_mode"] == mode
        ]

    lines = [
        GENERATED_HEADER,
        "",
        "// 能力位 ID、声明顺序与 failure_mode 派生清单的唯一事实源是",
        "// contracts/registries/crypto.yaml；本文件由生成器产出，禁止手改。",
        "// 探测实现（probeXxx）与分派表（capabilityDetectors）必须手写在 suite.go；",
        "// capabilities_test.go 断言生成物与分派表双向完备。",
        "",
        "package crypto",
        "",
        "const (",
    ]
    for entry in capabilities:
        lines.append(f'\t{_const_name(entry["id"])} = "{entry["id"]}"')
    lines.append(")")
    lines.append("")

    lines.append("// registryCapabilityOrder 是 YAML 声明顺序：启动探测与 /healthz 展示顺序稳定。")
    lines.append("var registryCapabilityOrder = []string{")
    for entry in capabilities:
        lines.append(f"\t{_const_name(entry['id'])},")
    lines.append("}")
    lines.append("")

    lines.append("// gmRequiredCapabilities 由 failure_mode=refuse 派生：gm 档缺失任一即拒绝启动。")
    lines.append("var gmRequiredCapabilities = []string{")
    for capability_id in ids_of("refuse"):
        lines.append(f"\t{_const_name(capability_id)},")
    lines.append("}")
    lines.append("")

    lines.append("// gmDegradableCapabilities 由 failure_mode=degrade 派生：缺失只把 /healthz 标记为 degraded。")
    lines.append("var gmDegradableCapabilities = []string{")
    for capability_id in ids_of("degrade"):
        lines.append(f"\t{_const_name(capability_id)},")
    lines.append("}")
    lines.append("")

    return _gofmt("\n".join(lines))


def _report_diff(existing: str, content: str) -> None:
    diff = list(
        difflib.unified_diff(
            existing.splitlines(),
            content.splitlines(),
            fromfile=str(OUTPUT_PATH.relative_to(ROOT)),
            tofile="generated",
            lineterm="",
        )
    )
    for line in diff[:12]:
        print(line)
    if len(diff) > 12:
        print(f"... 共 {len(diff)} 行差异（仅显示前 12 行）")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="检查模式：仅验证一致性")
    args = parser.parse_args()

    capabilities = _load_capabilities()
    content = _render_go(capabilities)
    relative = OUTPUT_PATH.relative_to(ROOT)

    if args.check:
        if not OUTPUT_PATH.exists():
            print(f"  NEW  {relative} (需生成)")
            print(f"FAIL: {relative} 不存在 — 运行 python3 scripts/gen_crypto_capabilities.py")
            sys.exit(1)
        existing = OUTPUT_PATH.read_text()
        if existing.strip() == content.strip():
            print(f"  OK  {relative}")
            print(f"PASS: {relative} 与 contracts/registries/crypto.yaml 零差异")
            return
        print(f"  DIFF {relative}")
        _report_diff(existing, content)
        print(
            f"FAIL: {relative} 与声明不一致 — "
            "运行 python3 scripts/gen_crypto_capabilities.py"
        )
        sys.exit(1)

    if OUTPUT_PATH.exists() and OUTPUT_PATH.read_text().strip() == content.strip():
        print(f"  OK  {relative}（已是最新）")
    else:
        OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT_PATH.write_text(content)
        print(f"  GEN {relative}")
    print(f"完成：{len(capabilities)} 个能力位（{', '.join(c['id'] for c in capabilities)}）")


if __name__ == "__main__":
    main()
