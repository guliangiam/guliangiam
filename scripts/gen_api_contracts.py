#!/usr/bin/env python3

"""从 surfaces.yaml 生成前端 API 契约 TS 类型

输入：contracts/registries/surfaces.yaml
输出：web/src/generated/api-contracts.ts；--check 模式 diff 并输出 PASS/FAIL
--check 行为：--check 模式比较当前 api-contracts.ts 与生成结果的差异，无差异时 PASS
消费方：check-generated-zero-diff.sh、CI"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

import yaml  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
REGISTRY_PATH = ROOT / "contracts/registries/surfaces.yaml"
TS_OUTPUT = ROOT / "web/src/generated/api-contracts.ts"


def _oxfmt(text: str, rel_path: str) -> str:
    """把渲染出的 TS 交给 oxfmt，使生成物本身就是 `pnpm run format:check` 的结果。"""
    oxfmt = ROOT / "web" / "node_modules" / ".bin" / "oxfmt"
    if not oxfmt.exists():
        raise RuntimeError("未找到 oxfmt：请先在 web/ 下执行 pnpm install")
    rel_in_web = rel_path[len("web/") :] if rel_path.startswith("web/") else rel_path
    try:
        proc = subprocess.run(
            [str(oxfmt), "-c", "oxfmt.json", f"--stdin-filepath={rel_in_web}"],
            input=text,
            capture_output=True,
            text=True,
            check=False,
            cwd=ROOT / "web",
        )
    except FileNotFoundError as exc:
        raise RuntimeError("未找到 oxfmt：请先在 web/ 下执行 pnpm install") from exc
    if proc.returncode != 0:
        raise RuntimeError(f"oxfmt 失败：{proc.stderr.strip()}")
    return proc.stdout


def _load() -> dict:
    if not REGISTRY_PATH.exists():
        print(f"ERROR: {REGISTRY_PATH} 不存在")
        sys.exit(1)
    with open(REGISTRY_PATH) as f:
        return yaml.safe_load(f) or {}


def _surface_for_prefix(prefix: str) -> str:
    """从 protocol_families 的 prefix 推断所属 surface。

    规则：
      - /oauth2/*, /.well-known/*, /cas/*, /scim/*, /api/v1/auth/*, /api/v1/saml/* → protocol
      - 其他 → management（auth 独立，没有对应前缀的归入 management）
    """
    protocol_prefixes = [
        "/oauth2/",
        "/.well-known/",
        "/cas/",
        "/scim/",
        "/api/v1/auth/",
        "/api/v1/saml/",
    ]
    for p in protocol_prefixes:
        if prefix.startswith(p):
            return "protocol"
    return "management"


def _render_ts(data: dict) -> str:
    """渲染 web/src/generated/api-contracts.ts。"""
    lines = []
    lines.append("// AUTO-GENERATED by scripts/gen_api_contracts.py")
    lines.append("// Do NOT edit manually — see contracts/registries/surfaces.yaml")
    lines.append("")

    # ── ApiSurface 三面联合类型 ──────────────────────────────────────
    surfaces = data.get("surfaces", []) or []
    surface_names = [s["surface"] for s in surfaces if "surface" in s]
    if not surface_names:
        surface_names = ["management", "authentication", "protocol"]

    lines.append("/** API 三面分类（唯一事实源：surfaces.yaml surfaces）。 */")
    union = " | ".join(f'"{s}"' for s in surface_names)
    lines.append(f"export type ApiSurface = {union};")
    lines.append("")

    # ── API_ENDPOINTS 按 protocol_families 分组 ─────────────────────
    families = data.get("protocol_families", []) or []
    lines.append("/**")
    lines.append(" * 协议面端点示例（按 family 分组）。")
    lines.append(" * 注意：这些是 typical_endpoints 示意列表，完整端点契约由")
    lines.append(" * scripts/gen_openapi.py 从 routes.go 生成 openapi/openapi.yaml。")
    lines.append(" */")
    lines.append(
        "export interface ApiEndpoint {"
    )
    lines.append("  method: string;")
    lines.append("  path: string;")
    lines.append("  surface: ApiSurface;")
    lines.append('  permission: string; // "" = 公开')
    lines.append("}")
    lines.append("")
    lines.append("export const API_ENDPOINTS: Record<string, ApiEndpoint[]> = {")

    for fam in families:
        family_name = fam.get("family", "")
        prefix = fam.get("prefix", "")
        typical = fam.get("typical_endpoints", []) or []
        surface = _surface_for_prefix(prefix)

        # 用 family 名作 key，转成合法 JS identifier
        key = fam.get("id", "").replace("①", "FAMILY_1").replace("②", "FAMILY_2").replace("③", "FAMILY_3").replace("④", "FAMILY_4").replace("⑤", "FAMILY_5").replace("⑥", "FAMILY_6")
        if not key.startswith("FAMILY_"):
            key = f"FAMILY_{key}"

        lines.append(f"  // {family_name}（{prefix}）")
        lines.append(f'  "{key}": [')
        for ep in typical:
            lines.append(
                f'    {{ method: "GET", path: "{ep}", surface: "{surface}", permission: "" }},'
            )
        lines.append("  ],")
        lines.append("")

    lines.append("};")
    lines.append("")

    # ── CONTRACT_ELEMENTS 三面契约组件映射 ────────────────────────────
    elements = data.get("contract_elements", {}) or {}
    error_body = elements.get("error_body", {}) or {}

    lines.append("/** 三面错误响应体类型。 */")
    lines.append("export const ERROR_BODY_BY_SURFACE: Record<ApiSurface, string> = {")
    for s in surface_names:
        body = error_body.get(s, "ErrorResponse")
        lines.append(f'  "{s}": "{body}",')
    lines.append("};")
    lines.append("")

    # 成功信封
    success = elements.get("success_envelope", {}) or {}
    if success:
        lines.append("/** 成功响应信封类型。 */")
        lines.append("export const SUCCESS_ENVELOPE = {")
        for k, v in success.items():
            lines.append(f'  {k}: "{v}",')
        lines.append("} as const;")
        lines.append("")

    return _oxfmt("\n".join(lines).rstrip() + "\n", "web/src/generated/api-contracts.ts")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="检查模式")
    args = parser.parse_args()

    data = _load()
    ts_content = _render_ts(data)

    if args.check:
        if not TS_OUTPUT.exists():
            print(f"  NEW  {TS_OUTPUT.relative_to(ROOT)}")
            print("FAIL: 需要重新生成")
            sys.exit(1)
        if TS_OUTPUT.read_text().strip() != ts_content.strip():
            print(f"  DIFF {TS_OUTPUT.relative_to(ROOT)}")
            print("FAIL: 与注册表不一致")
            sys.exit(1)
        print(f"  OK   {TS_OUTPUT.relative_to(ROOT)}")
        print("PASS: 生成物零差异")
        return

    TS_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    TS_OUTPUT.write_text(ts_content)
    print(f"GEN  {TS_OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
