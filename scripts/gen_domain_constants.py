#!/usr/bin/env python3
"""gen_domain_constants.py — 从 state-machines.yaml 生成 Go 领域状态常量骨架

唯一事实源：contracts/registries/state-machines.yaml
生成物：internal/domain/{module}/state_generated.go（禁止手改，重新生成覆盖）

每个有状态机的 domain 产出：
  - type {Name}State string
  - const {Name}{StateXxx} {Name}State = "xxx"
  - var All{Name}States = [...]
  - func IsValid({Name}State) bool

Usage:
  python3 scripts/gen_domain_constants.py           # 生成到 internal/domain/
  python3 scripts/gen_domain_constants.py --check    # 检查生成物是否与声明一致（零差异门禁）

输入：contracts/registries/state-machines.yaml
输出：internal/domain/{module}/state_generated.go、web/src/generated/state-machines.ts；--check 模式零差异门禁
--check 行为：--check 模式比较 Go 与 TS 生成物与声明的差异，无差异时 PASS
消费方：check-generated-zero-diff.sh、CI
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

import yaml  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
STATE_MACHINE_PATH = ROOT / "contracts/registries/state-machines.yaml"
OUTPUT_DIR = ROOT / "internal/domain"


def _gofmt(text: str) -> str:
    """把渲染出的 Go 源码交给 gofmt，使生成物本身就是 gofmt 结果。

    模板手工对齐（4 空格缩进 + 定宽列）永远不等于 gofmt 输出，此前只是没人
    跑过 `gofmt -l`，产物因此带格式债；门禁补上后必须由生成器负责格式化，
    否则「重新生成」与「格式化」会互相推翻。
    """
    try:
        proc = subprocess.run(["gofmt"], input=text, capture_output=True, text=True, check=False)
    except FileNotFoundError as exc:
        raise RuntimeError("未找到 gofmt：生成物必须等于 gofmt 输出，请安装 Go 工具链") from exc
    if proc.returncode != 0:
        raise RuntimeError(f"gofmt 失败：{proc.stderr.strip()}")
    return proc.stdout


def _snake_to_pascal(name: str) -> str:
    """snake_case → PascalCase。"""
    return "".join(p.capitalize() for p in name.replace("-", "_").split("_"))


def _load_sm() -> dict:
    if not STATE_MACHINE_PATH.exists():
        print(f"ERROR: {STATE_MACHINE_PATH} 不存在")
        sys.exit(1)
    with open(STATE_MACHINE_PATH) as f:
        return yaml.safe_load(f) or {}


def _render_go(module: str, sm_entry: dict, skip_behaviors: bool = False) -> str:
    """渲染单个 domain 的 Go 状态常量文件。

    skip_behaviors=True 时不生成 IsValid / CanTransitionTo（包目录已有手写 state_machine.go，
    开发者在那里维护业务前置条件、TryTransition 等更完备的函数）。
    """
    states = sm_entry.get("states", [])
    transitions = sm_entry.get("transitions", {})
    terminal = set(sm_entry.get("terminal", []))

    # 从 table_name 推导包名和类型名
    table = sm_entry.get("table", module)
    # table 可能是字符串或列表
    if isinstance(table, list):
        table_name = table[0] if table else module
    else:
        table_name = table
    # 去掉 guliangiam. 前缀
    short_table = table_name.split(".")[-1] if "." in table_name else table_name

    # domain 包名 = table 名复数形式简化
    # 例如 orders → orders, access_tokens → tokens
    pkg = _derive_package(short_table, module)
    type_name = _snake_to_pascal(pkg) + "State"

    lines = []
    lines.append("// Code generated by scripts/gen_domain_constants.py. DO NOT EDIT.")
    lines.append(f"// Source: contracts/registries/state-machines.yaml §{module}")
    lines.append(f"// Table: {table_name}")
    lines.append("")
    lines.append(f"package {pkg}")
    lines.append("")
    lines.append(f"// {type_name} — {pkg} 状态机枚举。")
    lines.append(f"// 唯一事实源：contracts/registries/state-machines.yaml §{module}")
    lines.append(f"// CHECK 约束：{sm_entry.get('check_constraint', f'ck_{pkg}_state')}")
    lines.append(f"type {type_name} string")
    lines.append("")
    lines.append("const (")
    for s in states:
        const_name = _snake_to_pascal(s)
        suffix = "_State" if not const_name.endswith("State") else ""
        comment = " // 终态" if s in terminal else ""
        lines.append(f"    {type_name}{const_name}{suffix} {type_name} = \"{s}\"{comment}")
    lines.append(")")
    lines.append("")
    lines.append(f"// All{type_name} 列出所有合法状态（用于 CHECK 约束 / migration 验证）。")
    lines.append(f"var All{type_name} = []{type_name}{{")
    for s in states:
        const_name = _snake_to_pascal(s)
        suffix = "_State" if not const_name.endswith("State") else ""
        lines.append(f"    {type_name}{const_name}{suffix},")
    lines.append("}")
    lines.append("")

    # IsValid —— 仅在 skip_behaviors=False 时生成
    if not skip_behaviors:
        lines.append(f"// IsValid 报告 s 是否属于已知状态集合。")
        lines.append(f"func IsValid(s string) bool {{")
        lines.append(f"    switch {type_name}(s) {{")
        for s in states:
            const_name = _snake_to_pascal(s)
            suffix = "_State" if not const_name.endswith("State") else ""
            lines.append(f"    case {type_name}{const_name}{suffix}:")
            lines.append("        return true")
        lines.append('    case "":')
        lines.append("        return false")
        lines.append("    default:")
        lines.append("        return false")
        lines.append("    }")
        lines.append("}")
        lines.append("")

    # CanTransitionTo（骨架——只检查 transition map，业务逻辑由开发者补充）
    if transitions and not skip_behaviors:
        lines.append(f"// CanTransitionTo 检查从当前状态到目标状态是否合法。")
        lines.append(f"// 骨架由生成器产出，业务前置条件（如 paid_at 非空）由开发者补充。")
        lines.append(f"func CanTransitionTo(from, to {type_name}) bool {{")
        lines.append(f"    allowed, ok := {_transitions_map_go(transitions, type_name)}")
        lines.append("    if !ok {")
        lines.append("        return false // 当前状态无任何出边（可能是终态）")
        lines.append("    }")
        lines.append("    for _, t := range allowed {")
        lines.append("        if t == to {")
        lines.append("            return true")
        lines.append("        }")
        lines.append("    }")
        lines.append("    return false")
        lines.append("}")
        lines.append("")

    return _gofmt("\n".join(lines))


def _derive_package(table: str, module: str) -> str:
    """从表名派生 Go package 名。

    规则：
      - sessions -> sessions
      - access_tokens / refresh_tokens / authorization_codes -> tokens
      - orders / payments / subscriptions -> 各自独立包
      - 其余按模块名
    """
    token_tables = {"access_tokens", "refresh_tokens", "authorization_codes"}
    if table in token_tables:
        return "tokens"
    return table  # 默认：表名即包名


def _transitions_map_go(transitions: dict, type_name: str) -> str:
    """把 transition dict 渲染成 Go map。"""
    cases = []
    for from_state, to_list in transitions.items():
        if not to_list:
            continue
        const_from = _snake_to_pascal(from_state)
        suffix_from = "_State" if not const_from.endswith("State") else ""
        lines = [f"        {type_name}{const_from}{suffix_from}: {{"]
        for t in to_list:
            const_t = _snake_to_pascal(t)
            suffix_t = "_State" if not const_t.endswith("State") else ""
            lines.append(f"            {type_name}{const_t}{suffix_t},")
        lines.append("        },")
        cases.append("\n".join(lines))
    if not cases:
        return f"map[{type_name}][]{type_name}{{}}[from]"
    inner = "\n".join(cases)
    return f"map[{type_name}][]{type_name}{{\n{inner}\n    }}[from]"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="检查模式：仅验证一致性")
    args = parser.parse_args()

    sm = _load_sm()
    targets = [k for k, v in sm.items() if isinstance(v, dict) and v.get("states")]

    generated_count = 0
    diff_count = 0

    for module in sorted(targets):
        entry = sm[module]

        # 推导包路径（先算路径再渲染，才能检测手写 state_machine.go）
        table = entry.get("table", module)
        if isinstance(table, list):
            table_name = table[0]
        else:
            table_name = table
        short_table = table_name.split(".")[-1] if "." in table_name else table_name
        pkg = _derive_package(short_table, module)
        pkg_dir = OUTPUT_DIR / pkg
        out_path = pkg_dir / "state_generated.go"

        # codegen: false 表示该状态机由声明层保留、不产出 Go 包（无消费者且无
        # 单源价值时使用）。零差异门禁同时验证文件不存在。
        if entry.get("codegen") is False:
            if args.check:
                if out_path.exists():
                    print(f"  STALE {out_path.relative_to(ROOT)} (codegen:false，应删除)")
                    diff_count += 1
                else:
                    print(f"  SKIP  {out_path.relative_to(ROOT)} (codegen:false)")
            else:
                if out_path.exists():
                    out_path.unlink()
                    try:
                        pkg_dir.rmdir()
                    except OSError:
                        pass
                    print(f"  DEL  {out_path.relative_to(ROOT)} (codegen:false)")
            continue

        # 如果包目录已有手写 state_machine.go，skip_behaviors=True 避免函数名冲突
        skip_behaviors = (pkg_dir / "state_machine.go").exists()
        content = _render_go(module, entry, skip_behaviors=skip_behaviors)

        if args.check:
            if out_path.exists():
                existing = out_path.read_text()
                if existing.strip() == content.strip():
                    print(f"  OK  {out_path.relative_to(ROOT)}")
                else:
                    print(f"  DIFF {out_path.relative_to(ROOT)}")
                    diff_count += 1
            else:
                print(f"  NEW  {out_path.relative_to(ROOT)} (需生成)")
                diff_count += 1
        else:
            out_path.parent.mkdir(parents=True, exist_ok=True)
            out_path.write_text(content)
            print(f"  GEN  {out_path.relative_to(ROOT)}")
            generated_count += 1

    print()
    if args.check:
        if diff_count:
            print(f"FAIL: {diff_count} 个文件需要重新生成")
            sys.exit(1)
        else:
            print(f"PASS: 全部 {len(targets)} 个状态机常量文件与声明一致")
    else:
        print(f"完成：生成 {generated_count} 个 Go 状态常量文件")


if __name__ == "__main__":
    main()
