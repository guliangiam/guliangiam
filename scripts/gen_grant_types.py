#!/usr/bin/env python3
"""Generate the grant-type closed sets from contracts/registries/grant-types.yaml.

One registry drives three consumers so the console selector, the API closed set,
DCR registration and OIDC discovery cannot drift apart (OPEN-API-68):

  * console   -> applications.allowedClientGrantTypes + web selector
  * dcr       -> applications.allowedDCRGrantTypes
  * discovery -> auth.discoveryGrantTypesSupported
"""
import argparse
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "contracts" / "registries" / "grant-types.yaml"
GO_APP = ROOT / "internal" / "app" / "applications" / "grant_types_gen.go"
GO_AUTH = ROOT / "internal" / "app" / "auth" / "oidc_grant_types_gen.go"
TS = ROOT / "web" / "src" / "pages" / "applications" / "tabs" / "grant-types.generated.ts"


def load_sets():
    data = yaml.safe_load(REGISTRY.read_text(encoding="utf-8"))
    grants = data.get("grants") or []
    if not grants:
        raise SystemExit("grant-types.yaml: grants must not be empty")
    seen = set()
    sets = {"console": [], "dcr": [], "discovery": []}
    for entry in grants:
        value = str(entry.get("value") or "").strip()
        if not value:
            raise SystemExit("grant-types.yaml: empty grant value")
        if value in seen:
            raise SystemExit(f"grant-types.yaml: duplicate grant {value}")
        seen.add(value)
        for key in sets:
            if entry.get(key):
                sets[key].append(value)
    for key, values in sets.items():
        if not values:
            raise SystemExit(f"grant-types.yaml: {key} set must not be empty")
    return sets


def go_list(values):
    body = "".join(f'\t"{value}",\n' for value in values)
    return "[]string{\n" + body + "}"


def render_go_app(sets):
    return (
        "// Code generated by scripts/gen_grant_types.py from contracts/registries/grant-types.yaml; DO NOT EDIT.\n\n"
        "package applications\n\n"
        "// allowedClientGrantTypes is the console/API closed set: only grants the\n"
        "// token endpoint can actually redeem.\n"
        f"var allowedClientGrantTypes = {go_list(sets['console'])}\n\n"
        "// allowedDCRGrantTypes is the RFC 7591 registration subset.\n"
        f"var allowedDCRGrantTypes = {go_list(sets['dcr'])}\n"
    )


def render_go_auth(sets):
    return (
        "// Code generated by scripts/gen_grant_types.py from contracts/registries/grant-types.yaml; DO NOT EDIT.\n\n"
        "package auth\n\n"
        "// discoveryGrantTypesSupported is advertised in OIDC discovery.\n"
        f"var discoveryGrantTypesSupported = {go_list(sets['discovery'])}\n"
    )


def ts_array(values):
    body = "".join(f'  "{value}",\n' for value in values)
    return "[\n" + body + "] as const"


def render_ts(sets):
    return (
        "// Code generated by scripts/gen_grant_types.py from contracts/registries/grant-types.yaml; DO NOT EDIT.\n\n"
        f"export const consoleGrantTypes = {ts_array(sets['console'])};\n\n"
        f"export const dcrGrantTypes = {ts_array(sets['dcr'])};\n\n"
        f"export const discoveryGrantTypes = {ts_array(sets['discovery'])};\n"
    )


def write_or_check(path, content, check):
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if check:
        if current != content:
            print(f"DIFF {path.relative_to(ROOT)}")
            return False
        return True
    path.write_text(content, encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")
    return True


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    sets = load_sets()
    ok = True
    ok &= write_or_check(GO_APP, render_go_app(sets), args.check)
    ok &= write_or_check(GO_AUTH, render_go_auth(sets), args.check)
    ok &= write_or_check(TS, render_ts(sets), args.check)
    if not ok:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
