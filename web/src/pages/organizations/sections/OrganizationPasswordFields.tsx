/**
 * 组织密码策略分区 —— 创建页与详情页共用。
 *
 * 详情页额外承载 `PasswordPolicy` 的 10 个标准键（6 个复杂度复选框 +
 * 最小/最大长度、历史检查数、过期天数）与扩展策略 JSON；创建接口不接收
 * 这些字段，故只在 `mode === "edit"` 时渲染。扩展 JSON 仅承载标准键之外
 * 的特殊策略，标准键的读取/回写见 ../organization-payload.ts。
 */
import { Checkbox, Col, Divider, Form, Input, InputNumber, Row, Select } from "antd";
import { useTranslation } from "react-i18next";
import { ConditionalField } from "@/shared/ui/ConditionalField";
import { GlFormRow } from "@/shared/ui/GlForm";
import { PasswordGeneratorInput } from "@/shared/ui/PasswordGenerator";
import { StructuredJsonField } from "../StructuredJsonEditor";
import type { OrganizationSectionMode } from "./types";

const passwordTypeOptions = [
  { label: "plain", value: "plain" },
  { label: "salt", value: "salt" },
  { label: "sha512-salt", value: "sha512-salt" },
  { label: "md5-salt", value: "md5-salt" },
  { label: "bcrypt", value: "bcrypt" },
  { label: "pbkdf2-salt", value: "pbkdf2-salt" },
  { label: "argon2id", value: "argon2id" },
  { label: "pbkdf2-django", value: "pbkdf2-django" },
];

const passwordObfuscatorTypeOptions = [
  { label: "Plain", value: "Plain" },
  { label: "AES", value: "AES" },
  { label: "SM4", value: "SM4" },
];

/** 设计文档规定的密码选项闭集（创建与编辑共用）。 */
const passwordOptionsChoices = ["AtLeast6", "AtLeast8", "Aa123", "SpecialChar", "NoRepeat"].map(
  (value) => ({ label: value, value }),
);

/** 复杂度复选框：表单字段名 → resource 命名空间标签键。 */
const complexityRules = [
  { name: "passwordRequireUppercase", labelKey: "passwordRequireUppercase" },
  { name: "passwordRequireLowercase", labelKey: "passwordRequireLowercase" },
  { name: "passwordRequireDigit", labelKey: "passwordRequireDigit" },
  { name: "passwordRequireSpecial", labelKey: "passwordRequireSpecial" },
  { name: "passwordRejectCommonPasswords", labelKey: "passwordRejectCommonPasswords" },
  { name: "passwordRejectUsername", labelKey: "passwordRejectUsername" },
] as const;

type OrganizationPasswordFieldsProps = {
  mode: OrganizationSectionMode;
};

export function OrganizationPasswordFields({ mode }: OrganizationPasswordFieldsProps) {
  const { t: tc } = useTranslation("common");
  const { t: tr } = useTranslation("resource");
  const editable = mode === "edit";
  const keepCurrent = tc("leaveEmptyToKeepCurrent");
  return (
    <Row gutter={16}>
      <Col xs={24} md={12}>
        <Form.Item name="passwordType" initialValue="argon2id">
          <GlFormRow label={tr("organization.passwordType")}>
            <Select allowClear options={passwordTypeOptions} />
          </GlFormRow>
        </Form.Item>
      </Col>
      <Col xs={24} md={12}>
        <Form.Item name="passwordSalt">
          <GlFormRow label={tr("organization.passwordSalt")}>
            <Input
              placeholder={editable ? keepCurrent : tr("organization.passwordSaltAutoGenerated")}
            />
          </GlFormRow>
        </Form.Item>
      </Col>
      <Col xs={24} md={12}>
        <Form.Item name="passwordObfuscatorType" initialValue="Plain">
          <GlFormRow label={tr("organization.passwordObfuscatorType")}>
            <Select allowClear options={passwordObfuscatorTypeOptions} />
          </GlFormRow>
        </Form.Item>
      </Col>
      <ConditionalField
        dependencies={["passwordObfuscatorType"]}
        when={(v) => !!v.passwordObfuscatorType && v.passwordObfuscatorType !== "Plain"}
      >
        <Col xs={24} md={12}>
          <Form.Item name="passwordObfuscatorKey">
            <GlFormRow label={tr("organization.passwordObfuscatorKey")}>
              <Input.Password placeholder={editable ? keepCurrent : undefined} />
            </GlFormRow>
          </Form.Item>
        </Col>
      </ConditionalField>
      <Col xs={24} md={12}>
        <Form.Item name="passwordOptions">
          <GlFormRow label={tr("organization.passwordOptions")}>
            <Select mode="multiple" allowClear options={passwordOptionsChoices} />
          </GlFormRow>
        </Form.Item>
      </Col>
      {editable && (
        <>
          <Col span={24}>
            <Divider titlePlacement="left" plain style={{ marginTop: 0 }}>
              {tr("organization.passwordRulesSection")}
            </Divider>
          </Col>
          {complexityRules.map((rule) => (
            <Col xs={24} md={12} key={rule.name}>
              <Form.Item name={rule.name} valuePropName="checked">
                <GlFormRow label={tr(`organization.${rule.labelKey}`)}>
                  <Checkbox />
                </GlFormRow>
              </Form.Item>
            </Col>
          ))}
          <Col xs={24} md={12}>
            <Form.Item
              name="passwordMinLength"
              rules={[
                {
                  required: true,
                  message: tr("organization.passwordMinLengthRange", { min: 6, max: 128 }),
                },
              ]}
            >
              <GlFormRow label={tr("organization.passwordMinLength")} required>
                <InputNumber min={6} max={128} style={{ width: "100%" }} />
              </GlFormRow>
            </Form.Item>
          </Col>
          <Col xs={24} md={12}>
            <Form.Item
              name="passwordMaxLength"
              rules={[
                {
                  required: true,
                  message: tr("organization.passwordMaxLengthRange", { min: 8, max: 1024 }),
                },
              ]}
            >
              <GlFormRow label={tr("organization.passwordMaxLength")} required>
                <InputNumber min={8} max={1024} style={{ width: "100%" }} />
              </GlFormRow>
            </Form.Item>
          </Col>
          <Col xs={24} md={12}>
            <Form.Item
              name="passwordHistoryCount"
              rules={[
                {
                  required: true,
                  message: tr("organization.passwordHistoryCountRange", { min: 0, max: 24 }),
                },
              ]}
            >
              <GlFormRow
                label={tr("organization.passwordHistoryCount")}
                required
                extra={tr("organization.passwordHistoryCountHint")}
              >
                <InputNumber min={0} max={24} style={{ width: "100%" }} />
              </GlFormRow>
            </Form.Item>
          </Col>
          <Col xs={24} md={12}>
            <Form.Item
              name="passwordExpireDays"
              rules={[
                {
                  required: true,
                  message: tr("organization.passwordExpireDaysRange", { min: 0, max: 365 }),
                },
              ]}
            >
              <GlFormRow label={tr("organization.passwordExpireDays")} required>
                <InputNumber
                  min={0}
                  max={365}
                  style={{ width: "100%" }}
                  suffix={tr("organization.daysUnit")}
                />
              </GlFormRow>
            </Form.Item>
          </Col>
          <Col span={24}>
            <StructuredJsonField
              name="passwordPolicyExtraJson"
              label={tr("organization.passwordPolicyExtraJson")}
              rows={4}
            />
          </Col>
        </>
      )}
      <Col xs={24} md={12}>
        <Form.Item name="defaultPassword">
          <GlFormRow label={tr("organization.defaultPassword")}>
            <PasswordGeneratorInput
              placeholder={
                editable
                  ? `${tr("organization.placeholder.defaultPassword")} · ${keepCurrent}`
                  : tr("organization.placeholder.defaultPassword")
              }
            />
          </GlFormRow>
        </Form.Item>
      </Col>
      <Col xs={24} md={12}>
        <Form.Item name="masterPassword">
          <GlFormRow
            label={tr("organization.masterPassword")}
            extra={tr("organization.masterPasswordExtra")}
          >
            <PasswordGeneratorInput masked placeholder={keepCurrent} />
          </GlFormRow>
        </Form.Item>
      </Col>
      <Col xs={24} md={12}>
        <Form.Item name="masterVerificationCode">
          <GlFormRow label={tr("organization.masterVerificationCode")}>
            <Input.Password placeholder={keepCurrent} />
          </GlFormRow>
        </Form.Item>
      </Col>
    </Row>
  );
}
